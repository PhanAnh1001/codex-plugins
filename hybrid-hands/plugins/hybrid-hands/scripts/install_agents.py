#!/usr/bin/env python3
"""Generate bounded Codex agents from the canonical core profile (dry-run by default)."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import stat
import sys
import tempfile
from typing import Any

from hybrid_codex import AdapterError, PROFILES, run_core

MARKER = '# Generated by hybrid-hands Codex adapter'
AGENTS = {'code': ('hybrid-code', 'code', None),
          'collect.1': ('hybrid-collect-1', 'collect', 1),
          'collect.2': ('hybrid-collect-2', 'collect', 2)}
DATA_LAW = '''Không in/hiện giá trị `.env`, token, credential ở bất kỳ tầng nào; công cụ của plugin (`hand-ext doctor/run`, đọc hạn mức) được đọc file auth nội bộ, chỉ không được in giá trị. Brief giao hand ngoài chép nguyên văn luật này.
Không đọc `.env` bằng lệnh hay tool hiện giá trị: `cat`, `head`, `tail`, `grep`, `sed`, `awk`, `less`, `more`, `rg`, `Read`, kể cả có che phần sau dấu `=`.
Không đọc hay in token, auth.json, file credential. Không giao hand ngoài việc cần secret hay dữ liệu khách hàng. Chỉ dùng code và fixtures giả công khai được; không đọc transcript/log thật. Không gọi API trả phí, không tạo hay dùng API key.'''


def target_home(value: str | None) -> Path:
    home = Path(value if value is not None else os.environ.get('CODEX_HOME', str(Path.home() / '.codex')))
    if not home.is_absolute():
        raise AdapterError('codex home must be absolute')
    return home


def validate_rows(payload: dict[str, Any]) -> list[dict[str, Any]]:
    profile = payload.get('profile')
    if not isinstance(profile, str) or profile not in PROFILES or not isinstance(payload.get('roles'), dict):
        raise AdapterError('invalid profile roles')
    rows = []
    for key, (name, role, tier) in AGENTS.items():
        row = payload['roles'].get(key)
        if not isinstance(row, dict):
            raise AdapterError('missing profile role')
        if any(not isinstance(row.get(k), str) or not row[k].strip()
               for k in ('profile', 'role', 'provider', 'account', 'model', 'effort')):
            raise AdapterError('invalid profile role fields')
        if (row['profile'] != profile or row['role'] != role or 'tier' not in row
                or row['tier'] != tier or (tier is not None and type(row['tier']) is not int)):
            raise AdapterError('profile role mismatch')
        rows.append({k: row[k] for k in ('profile', 'role', 'tier', 'provider', 'account', 'model', 'effort')} | {'name': name})
    return rows


def render(row: dict[str, Any]) -> bytes:
    metadata = ', '.join(f'{key}={row[key]}' for key in ('profile', 'role', 'tier', 'account', 'model', 'effort'))
    notice = (f'Generated configuration: {metadata}. Caller must run pick again and verify the same '
              'configuration, current account and native capability before invocation. Generation is not native approval.')
    instructions = (notice + '\nYou are a bounded executor. Execute only the self-contained assigned packet. '
                    'Read applicable AGENTS.md and CLAUDE.md before editing. Do not spawn, delegate, use agent-management tools, '
                    'or communicate with other sessions. Do not commit, push, or perform destructive actions. '
                    'Do not make product, architecture, or security decisions; escalate uncertainty to the caller. '
                    'Return evidence in Vietnamese: result, changed files with path:line, actual commands/results, '
                    'assumptions and residual uncertainty.\n' + DATA_LAW)
    fields = {'name': row['name'], 'description': notice, 'model': row['model'],
              'model_reasoning_effort': row['effort'], 'developer_instructions': instructions}
    return (MARKER + '\n' + '\n'.join(f'{key} = {json.dumps(value, ensure_ascii=False)}' for key, value in fields.items()) + '\n').encode()


def preflight(path: Path, content: bytes) -> str:
    # Check every ancestor as well: a symlinked home/agents must never redirect writes.
    if any(parent.is_symlink() for parent in (path, *path.parents)):
        raise AdapterError('symlink destination refused')
    if not path.exists():
        return 'create'
    if not path.is_file():
        raise AdapterError('destination is not a regular file')
    current = path.read_bytes()
    if not current.startswith((MARKER + '\n').encode()):
        raise AdapterError('unmanaged destination refused')
    return 'unchanged' if current == content else 'update'


def atomic_write(path: Path, content: bytes, action: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    previous = path.stat() if action == 'update' else None
    if action == 'update':
        stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
        backup = path.with_name(path.name + '.bak.' + stamp)
        with backup.open('xb') as stream:
            os.chmod(backup, 0o600)
            if previous is not None:
                os.fchown(stream.fileno(), previous.st_uid, previous.st_gid)
            stream.write(path.read_bytes())
    fd, temporary = tempfile.mkstemp(prefix='.' + path.name + '.', dir=path.parent)
    try:
        os.fchmod(fd, stat.S_IRUSR | stat.S_IWUSR)
        if previous is not None:
            os.fchown(fd, previous.st_uid, previous.st_gid)
        with os.fdopen(fd, 'wb') as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def generate(cwd: str, core_cli: str | None, home: Path, apply: bool) -> tuple[list[dict[str, Any]], int]:
    payload, status = run_core('profile', cwd, core_cli)
    if status:
        return [], status
    rows = validate_rows(payload)
    planned = []
    result = []
    for row in rows:
        path = home / 'agents' / (row['name'] + '.toml')
        metadata = {key: row[key] for key in ('profile', 'role', 'tier', 'account', 'model', 'effort')}
        metadata['path'] = str(path)
        if row['provider'] != 'codex':
            result.append(metadata | {'status': 'skipped', 'skipped': 'provider is not codex'})
            continue
        content = render(row)
        action = preflight(path, content)
        planned.append((path, content, action))
        result.append(metadata | {'status': action if apply else 'dry-run-' + action, 'skipped': ''})
    if apply:
        for path, content, action in planned:
            if action != 'unchanged':
                atomic_write(path, content, action)
    return result, 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cwd', required=True)
    parser.add_argument('--core-cli')
    parser.add_argument('--codex-home')
    parser.add_argument('--apply', action='store_true')
    args = parser.parse_args(argv)
    try:
        result, status = generate(args.cwd, args.core_cli, target_home(args.codex_home), args.apply)
    except (AdapterError, OSError, ValueError, TypeError):
        print(json.dumps({'status': 'error', 'error': 'agent generation failed; no untrusted details emitted'}))
        return 2
    print(json.dumps({'agents': result}, ensure_ascii=False))
    return status


if __name__ == '__main__':
    sys.exit(main())
